#!/usr/bin/env bash
#
# Renders the app icon from its SVG sources (assets/icon/*.svg) into every
# size Android and the Linux desktop need. Run after editing the SVGs and
# commit the generated PNGs. Needs rsvg-convert (librsvg).

set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/_common.sh"

command -v rsvg-convert >/dev/null || die "rsvg-convert not found (pacman -S librsvg)"
SRC="$PROJECT_DIR/assets/icon"
RES="$PROJECT_DIR/android/app/src/main/res"

render() { rsvg-convert -w "$2" -h "$2" "$SRC/$1" -o "$3"; }

step "Android launcher icons"
# density: legacy size / adaptive layer size (108 dp)
for spec in mdpi:48:108 hdpi:72:162 xhdpi:96:216 xxhdpi:144:324 xxxhdpi:192:432; do
  IFS=: read -r density legacy layer <<<"$spec"
  dir="$RES/mipmap-$density"
  mkdir -p "$dir"
  render icon.svg "$legacy" "$dir/ic_launcher.png"
  render background.svg "$layer" "$dir/ic_launcher_background.png"
  render foreground.svg "$layer" "$dir/ic_launcher_foreground.png"
done

mkdir -p "$RES/mipmap-anydpi-v26"
cat > "$RES/mipmap-anydpi-v26/ic_launcher.xml" <<'XML'
<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-icons.sh -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@mipmap/ic_launcher_background" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
XML

step "Linux icon"
render icon.svg 512 "$SRC/icon.png"

echo "Done."

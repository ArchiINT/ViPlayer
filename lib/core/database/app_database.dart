import 'package:drift/drift.dart';
import 'package:drift_flutter/drift_flutter.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:path_provider/path_provider.dart';

import 'app_database.steps.dart';
import 'tables.dart';

part 'app_database.g.dart';

final appDatabaseProvider = Provider<AppDatabase>((ref) {
  final db = AppDatabase();
  ref.onDispose(db.close);
  return db;
});

@DriftDatabase(
  tables: [
    Tracks,
    Playlists,
    PlaylistEntries,
    PlayEvents,
    LibraryFolders,
    TrackFiles,
    SyncState,
    TrackAliases,
    ExcludedTracks,
  ],
)
class AppDatabase extends _$AppDatabase {
  AppDatabase([QueryExecutor? executor]) : super(executor ?? _openDefault());

  /// Bump on every schema change and add a step to [migration].
  ///
  /// Schema snapshots live in `drift_schemas/` and are verified by tests —
  /// run `scripts/db-schema.sh` after changing tables.dart.
  @override
  int get schemaVersion => 4;

  @override
  MigrationStrategy get migration => MigrationStrategy(
    onCreate: (m) async {
      await m.createAll();
      await _createIndexes();
      await _createSyncTriggers();
    },
    // One step per version, typed against that version's schema snapshot
    // (app_database.steps.dart is generated by scripts/db-schema.sh).
    onUpgrade: stepByStep(
      from1To2: (m, schema) async {
        await m.addColumn(schema.trackFiles, schema.trackFiles.coverId);
      },
      from2To3: (m, schema) async {
        await m.addColumn(schema.tracks, schema.tracks.localRev);
        await m.addColumn(schema.playlists, schema.playlists.localRev);
        await m.addColumn(
          schema.playlistEntries,
          schema.playlistEntries.localRev,
        );
        await m.addColumn(schema.playEvents, schema.playEvents.localRev);
        await m.createTable(schema.syncState);
        await m.createTable(schema.trackAliases);
        await _createSyncTriggers();
        // Give every existing row a revision so the first sync sends it.
        for (final table in syncedTableNames) {
          await customStatement('UPDATE $table SET updated_at = updated_at');
        }
      },
      from3To4: (m, schema) async {
        await m.createTable(schema.excludedTracks);
      },
    ),
    beforeOpen: (details) async {
      await customStatement('PRAGMA foreign_keys = ON');
    },
  );

  Future<void> _createIndexes() async {
    await customStatement(
      'CREATE INDEX IF NOT EXISTS idx_tracks_artist ON tracks (artist)',
    );
    await customStatement(
      'CREATE INDEX IF NOT EXISTS idx_entries_playlist '
      'ON playlist_entries (playlist_id, position)',
    );
    await customStatement(
      'CREATE INDEX IF NOT EXISTS idx_files_track ON track_files (track_id)',
    );
    await customStatement(
      'CREATE INDEX IF NOT EXISTS idx_events_played ON play_events (played_at)',
    );
  }

  /// Synced tables, in dependency order (referenced tables first).
  static const syncedTableNames = [
    'tracks',
    'playlists',
    'playlist_entries',
    'play_events',
  ];

  /// Every insert/update of a synced row stamps it with the next value of
  /// the database-wide `rev` sequence. Done in SQLite so no write path can
  /// forget it — including rows merged in from other devices.
  Future<void> _createSyncTriggers() async {
    await customStatement(
      "INSERT OR IGNORE INTO sync_state (key, value) VALUES ('rev', 0)",
    );
    for (final table in syncedTableNames) {
      const next = "UPDATE sync_state SET value = value + 1 WHERE key = 'rev';";
      String stamp(String t) =>
          'UPDATE $t SET local_rev = (SELECT value FROM sync_state '
          "WHERE key = 'rev') WHERE rowid = NEW.rowid;";
      await customStatement(
        'CREATE TRIGGER IF NOT EXISTS ${table}_rev_insert '
        'AFTER INSERT ON $table BEGIN $next ${stamp(table)} END',
      );
      // The WHEN clause skips the trigger's own local_rev update.
      await customStatement(
        'CREATE TRIGGER IF NOT EXISTS ${table}_rev_update '
        'AFTER UPDATE ON $table WHEN NEW.local_rev = OLD.local_rev '
        'BEGIN $next ${stamp(table)} END',
      );
    }
  }

  /// Latest value of the `rev` sequence.
  Future<int> currentRev() async {
    final row = await (select(
      syncState,
    )..where((s) => s.key.equals('rev'))).getSingleOrNull();
    return row?.value ?? 0;
  }

  /// The database lives in the app *support* directory (Linux:
  /// ~/.local/share/com.viplayer.app, Android: app-private storage), not in
  /// ~/Documents. App updates keep this directory intact.
  static QueryExecutor _openDefault() => driftDatabase(
    name: 'viplayer',
    native: const DriftNativeOptions(
      databaseDirectory: getApplicationSupportDirectory,
    ),
  );
}
